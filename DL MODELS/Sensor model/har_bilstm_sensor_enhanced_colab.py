def evaluate_accuracy(model, loader):
    model.eval()
    correct = total = 0
    with torch.inference_mode():
        for xb, yb in loader:
            xb = xb.to(device, non_blocking=(device.type == 'cuda'))
            logits = model(xb)
            correct += (logits.argmax(dim=1).cpu() == yb).sum().item()
            total += len(yb)
    return correct / max(total, 1)


def train_candidate(model_class, name):
    model = model_class(
        input_size=len(CHANNELS),
        hidden_size=HIDDEN_SIZE,
        num_classes=len(ACTIVITY_NAMES)
    ).to(device)
    loss_fn = nn.CrossEntropyLoss(label_smoothing=0.02)
    optimizer = torch.optim.AdamW(model.parameters(), lr=LEARNING_RATE, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='max', factor=0.5, patience=3, min_lr=1e-5
    )
    best_val = -1.0
    best_epoch = 0
    epochs_without_improvement = 0

    for epoch in range(MAX_EPOCHS):
        model.train()
        total_loss = 0.0
        for xb, yb in train_loader:
            xb = xb.to(device, non_blocking=(device.type == 'cuda'))
            yb = yb.to(device, non_blocking=(device.type == 'cuda'))
            optimizer.zero_grad(set_to_none=True)
            loss = loss_fn(model(xb), yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()
            total_loss += loss.item()

        val_accuracy = evaluate_accuracy(model, val_loader)
        scheduler.step(val_accuracy)
        average_loss = total_loss / max(len(train_loader), 1)
        print(f'{name} | Epoch {epoch + 1}: loss={average_loss:.4f}, val_acc={val_accuracy * 100:.2f}%')

        if val_accuracy > best_val:
            best_val = val_accuracy
            best_epoch = epoch + 1
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1
            if epochs_without_improvement >= PATIENCE:
                print(f'{name}: early stopping.')
                break

    return best_val, best_epoch


