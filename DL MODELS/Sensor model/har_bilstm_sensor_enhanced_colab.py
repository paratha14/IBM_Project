def load_split(split):
    signal_dir = DATA_DIR / split / 'Inertial Signals'
    signals = [
        np.loadtxt(signal_dir / f'{name}_{split}.txt', dtype=np.float32)
        for name in CHANNELS
    ]
    X = np.stack(signals, axis=-1)  # examples x time steps x sensor channels
    y = np.loadtxt(DATA_DIR / split / f'y_{split}.txt', dtype=np.int64) - 1
    return X, y

